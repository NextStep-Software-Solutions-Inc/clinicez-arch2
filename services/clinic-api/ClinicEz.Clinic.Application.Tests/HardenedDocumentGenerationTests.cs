    [Fact]
    public async Task IssueMedicalCertificateCommand_Should_Generate_Sequential_Numbers_Safely()
    {
        var testClinicId = Guid.NewGuid();
        var testTenantId = "tenant-test-01";
        var clinicContext = Substitute.For<IClinicContext>();
        clinicContext.ClinicId.Returns(testClinicId);
        clinicContext.TenantId.Returns(testTenantId);

        var (db, uow, sieve) = TestDbHelper.CreateTestContext(clinicContext);
        var medCertRepo = TestDbHelper.CreateRepository<MedicalCertificate>(db, sieve);

        var handler = Phase3TestKit.MedCert(medCertRepo, uow, clinicContext, db);

        var patientId = Guid.NewGuid();
        var doctorId = Guid.NewGuid();

        var cert1 = await handler.Handle(new IssueMedicalCertificateCommand(
            patientId,
            "Patient One",
            null,
            doctorId,
            "Dr. Ramos",
            "0056789",
            null,
            "Hypertension Stage 1",
            null
        ), CancellationToken.None);

        var cert2 = await handler.Handle(new IssueMedicalCertificateCommand(
            patientId,
            "Patient Two",
            null,
            doctorId,
            "Dr. Ramos",
            "0056789",
            null,
            "Type 2 Diabetes",
            null
        ), CancellationToken.None);

        cert1.CertificateNumber.Should().EndWith("-0001");
        cert2.CertificateNumber.Should().EndWith("-0002");
    }

