import * as DocumentPicker from 'expo-document-picker';
import { Platform } from 'react-native';

export interface PickLogoResult {
  dataUri?: string;
  error?: string;
}

/**
 * Prompts the user to pick an image file for the clinic logo.
 * Validates the image type and size, and converts it to a persistent Data URI.
 */
export async function pickClinicLogo(): Promise<PickLogoResult | null> {
  try {
    const result = await DocumentPicker.getDocumentAsync({
      type: ['image/png', 'image/jpeg', 'image/webp', 'image/svg+xml', 'image/*'],
      copyToCacheDirectory: true,
      multiple: false,
    });

    if (result.canceled || !result.assets || result.assets.length === 0) {
      return null;
    }

    const asset = result.assets[0];

    // Check size limit (max 2 MB)
    if (asset.size && asset.size > 2 * 1024 * 1024) {
      return { error: 'Please choose an image file smaller than 2 MB.' };
    }

    // Web: If asset.file is available, convert directly via FileReader
    if ((asset as any).file && typeof FileReader !== 'undefined') {
      const dataUri = await new Promise<string>((resolve, reject) => {
        const reader = new FileReader();
        reader.onload = () => resolve(reader.result as string);
        reader.onerror = () => reject(new Error('Failed to read image file.'));
        reader.readAsDataURL((asset as any).file);
      });
      return { dataUri };
    }

    // Web: Fetch blob URI if generated by browser
    if (Platform.OS === 'web' && asset.uri) {
      if (asset.uri.startsWith('data:')) {
        return { dataUri: asset.uri };
      }
      try {
        const response = await fetch(asset.uri);
        const blob = await response.blob();
        const dataUri = await new Promise<string>((resolve, reject) => {
          const reader = new FileReader();
          reader.onload = () => resolve(reader.result as string);
          reader.onerror = () => reject(new Error('Failed to convert blob to data URI.'));
          reader.readAsDataURL(blob);
        });
        return { dataUri };
      } catch {
        return { dataUri: asset.uri };
      }
    }

    // Native: Read as base64 string via expo-file-system
    try {
      const FileSystem = await import('expo-file-system');
      if (FileSystem && FileSystem.readAsStringAsync) {
        const base64 = await FileSystem.readAsStringAsync(asset.uri, {
          encoding: FileSystem.EncodingType.Base64,
        });
        const mime = asset.mimeType || 'image/png';
        return { dataUri: `data:${mime};base64,${base64}` };
      }
    } catch {
      // Fallback to raw uri if FileSystem is unavailable
    }

    return { dataUri: asset.uri };
  } catch (err: any) {
    return { error: err?.message || 'Failed to select image.' };
  }
}
